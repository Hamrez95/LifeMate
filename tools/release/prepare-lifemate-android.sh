#!/usr/bin/env bash
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
app_dir="$repo_root/lifemate"

fail() {
  echo "::error::$*" >&2
  exit 1
}

command -v flutter >/dev/null 2>&1 || fail "flutter is required"
command -v python3 >/dev/null 2>&1 || fail "python3 is required"
[[ -f "$app_dir/pubspec.yaml" ]] || fail "lifemate/pubspec.yaml is missing"

(
  cd "$app_dir"
  flutter create \
    --platforms=android \
    --org com.mylifemate \
    --project-name lifemate \
    .
)

# The repository owns the real tests and analysis behavior. Remove only files
# generated by `flutter create` that could mask that surface.
rm -f "$app_dir/test/widget_test.dart" "$app_dir/analysis_options.yaml"

manifest="$app_dir/android/app/src/main/AndroidManifest.xml"
gradle="$app_dir/android/app/build.gradle.kts"
[[ -f "$manifest" ]] || fail "generated AndroidManifest.xml is missing"
[[ -f "$gradle" ]] || fail "generated Android build.gradle.kts is missing"

python3 - "$manifest" <<'PY'
from pathlib import Path
import sys

manifest = Path(sys.argv[1])
text = manifest.read_text()
open_tag = '<manifest xmlns:android="http://schemas.android.com/apk/res/android">'
if open_tag not in text:
    raise SystemExit('generated LifeMate manifest contract changed')
if 'android.permission.INTERNET' not in text:
    text = text.replace(
        open_tag,
        open_tag + '\n    <uses-permission android:name="android.permission.INTERNET" />',
        1,
    )
if 'android:label="lifemate"' not in text:
    raise SystemExit('generated LifeMate label contract changed')
text = text.replace('android:label="lifemate"', 'android:label="LifeMate"', 1)
manifest.write_text(text)
PY

grep -Fq 'applicationId = "com.mylifemate.lifemate"' "$gradle" || \
  fail "LifeMate Android applicationId is not isolated."
grep -Fq 'android:label="LifeMate"' "$manifest" || \
  fail "LifeMate Android display name is missing."
grep -Fq 'android.permission.INTERNET' "$manifest" || \
  fail "LifeMate Android network permission is missing."
