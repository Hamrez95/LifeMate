const LifeMateMessageCatalog lifeMateSubscriptionCenterMessages =
    LifeMateMessageCatalog(<String, Map<String, String>>{
  'en': lifeMateSubscriptionCenterEnglishMessages,
  'fa': lifeMateSubscriptionCenterPersianMessages,
});

extension LifeMateSubscriptionCenterLocalization on BuildContext {
  String subscriptionTr(
    String key, {
    Map<String, Object?> params = const <String, Object?>{},
  }) =>
      lifeMateSubscriptionCenterMessages.text(
        key,
        locale: lifeMateLocale.locale,
        params: params,
      );
}

/// Resolves known server-owned labels and policy keys into the current UI
/// locale. The server remains authoritative for entitlement state and values;
/// this catalogue only translates labels. Unknown machine keys use a safe
/// localized fallback instead of leaking raw identifiers into the UI.
String lifeMateSubscriptionServerLabel(
  String? value, {
  required Locale locale,
  required String fallback,
  required bool policy,
}) {
  final raw = value?.trim();
  if (raw == null || raw.isEmpty) return fallback;

  final key = switch (raw.toLowerCase()) {
    'period calendar' => 'subscription.entitlement.periodCalendar',
    'wellmate + caremate' ||
    'wellmate and caremate' =>
      'subscription.entitlement.wellCare',
    'cocoonmate' => 'subscription.entitlement.cocoon',
    'trial.days' => 'subscription.policy.trialDays',
    'pricing.family' => 'subscription.policy.familyPricing',
    'premium.locked_features' => 'subscription.policy.lockedFeatures',
    'free.visits.max' => 'subscription.policy.freeVisits',
    'free.medications.max' => 'subscription.policy.freeMedications',
    'free.caremate_people.max' => 'subscription.policy.carePeople',
    'free.owner_caregivers.max' => 'subscription.policy.ownerCaregivers',
    _ => null,
  };
  if (key != null) {
    return lifeMateSubscriptionCenterMessages.text(key, locale: locale);
  }

  // Dotted snake-case values are server identifiers, not user-facing labels.
  if (RegExp(r'^[a-z][a-z0-9_]*(?:\.[a-z0-9_]+)+$').hasMatch(raw)) {
    return fallback;
  }

  // The current subscription endpoint sends a small set of English display
  // names. Preserve other server-provided names because they may be localized
  // labels from a newer catalogue.
  if (!policy && locale.languageCode == 'fa') {
    if (raw.toLowerCase().startsWith('period ')) return 'تقویم چرخه';
    if (raw.toLowerCase().startsWith('wellmate')) return 'ول‌میت و کرمیت';
    if (raw.toLowerCase().startsWith('cocoon')) return 'کوکون‌میت';
  }
  return raw;
}
